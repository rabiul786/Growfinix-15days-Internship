# Task 2 - List, tuple, dictionary and set examples

subjects = ["Maths", "Physics", "Chemistry"]   # list (can change)
subjects.append("English")

days = ("Mon", "Wed", "Fri")                   # tuple (cannot change)

student = {"name": "Rahim", "age": 20}         # dictionary
student["course"] = "B.Tech"

skills = {"python", "sql", "python"}           # set (no duplicates)

print("List:", subjects)
print("Tuple:", days)
print("Dictionary:", student)
print("Set:", skills)
